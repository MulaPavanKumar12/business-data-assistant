"""Application settings loaded from environment variables (and an optional .env file).

All configuration lives here so the rest of the code never reads ``os.environ``
directly. That makes settings easy to override in tests and keeps secrets in
one auditable place.
"""

from __future__ import annotations

from functools import lru_cache
from urllib.parse import quote_plus

from pydantic import Field
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """Typed application settings.

    Two database identities are deliberately kept separate:

    * **admin** (``POSTGRES_USER``) owns the schema and is used only for seeding
      and, later, for writing audit logs.
    * **read-only** (``READONLY_DB_USER``) is the only identity used to execute
      SQL generated by the LLM.
    """

    model_config = SettingsConfigDict(
        env_file=(".env", "../.env"),
        env_file_encoding="utf-8",
        extra="ignore",
    )

    # --- Database connection -------------------------------------------------
    db_host: str = Field(default="localhost", alias="DB_HOST")
    db_port: int = Field(default=5432, alias="POSTGRES_PORT")
    db_name: str = Field(default="business_db", alias="POSTGRES_DB")

    admin_user: str = Field(default="bda_admin", alias="POSTGRES_USER")
    admin_password: str = Field(default="change_me_admin", alias="POSTGRES_PASSWORD")

    readonly_user: str = Field(default="bda_readonly", alias="READONLY_DB_USER")
    readonly_password: str = Field(default="change_me_readonly", alias="READONLY_DB_PASSWORD")

    # --- Seeding -------------------------------------------------------------
    seed_random_seed: int = Field(default=42, alias="SEED_RANDOM_SEED")
    seed_num_customers: int = Field(default=500, ge=10, alias="SEED_NUM_CUSTOMERS")
    seed_num_employees: int = Field(default=60, ge=15, alias="SEED_NUM_EMPLOYEES")
    seed_num_products: int = Field(default=120, ge=10, alias="SEED_NUM_PRODUCTS")
    seed_num_orders: int = Field(default=5000, ge=10, alias="SEED_NUM_ORDERS")

    # --- LLM -----------------------------------------------------------------
    llm_provider: str = Field(default="anthropic", alias="LLM_PROVIDER")  # anthropic | openai | ollama
    llm_model: str = Field(default="", alias="LLM_MODEL")  # empty = provider default
    llm_effort: str = Field(default="low", alias="LLM_EFFORT")  # Claude thinking effort
    llm_enable_fallbacks: bool = Field(default=True, alias="LLM_ENABLE_FALLBACKS")
    anthropic_api_key: str = Field(default="", alias="ANTHROPIC_API_KEY")
    openai_api_key: str = Field(default="", alias="OPENAI_API_KEY")
    openai_base_url: str = Field(default="", alias="OPENAI_BASE_URL")

    # --- Schema RAG ----------------------------------------------------------
    rag_backend: str = Field(default="hybrid", alias="RAG_BACKEND")  # hybrid | keyword
    chroma_path: str = Field(default="", alias="CHROMA_PATH")  # empty = in-memory
    rag_top_k: int = Field(default=4, ge=1, le=9, alias="RAG_TOP_K")

    # --- Query guardrails ----------------------------------------------------
    max_result_rows: int = Field(default=200, ge=1, le=5000, alias="MAX_RESULT_ROWS")
    query_timeout_ms: int = Field(default=5000, ge=100, alias="QUERY_TIMEOUT_MS")
    sql_repair_attempts: int = Field(default=1, ge=0, le=3, alias="SQL_REPAIR_ATTEMPTS")

    # --- Security ------------------------------------------------------------
    jwt_secret: str = Field(default="dev-only-change-me-to-a-long-random-string", alias="JWT_SECRET")
    jwt_expiry_minutes: int = Field(default=480, alias="JWT_EXPIRY_MINUTES")
    demo_user_password: str = Field(default="demo123", alias="DEMO_USER_PASSWORD")
    internal_api_key: str = Field(default="dev-internal-key", alias="INTERNAL_API_KEY")
    business_api_url: str = Field(default="http://localhost:8000/internal/v1", alias="BUSINESS_API_URL")
    pending_action_ttl_minutes: int = Field(default=15, alias="PENDING_ACTION_TTL_MINUTES")

    # --- Service -------------------------------------------------------------
    log_level: str = Field(default="INFO", alias="LOG_LEVEL")
    app_name: str = "Business Data Assistant"

    def _dsn(self, user: str, password: str) -> str:
        return f"postgresql://{quote_plus(user)}:{quote_plus(password)}@{self.db_host}:{self.db_port}/{self.db_name}"

    @property
    def admin_dsn(self) -> str:
        """Connection string for the schema owner (seeding / audit writes only)."""
        return self._dsn(self.admin_user, self.admin_password)

    @property
    def readonly_dsn(self) -> str:
        """Connection string for the least-privilege role that runs generated SQL."""
        return self._dsn(self.readonly_user, self.readonly_password)


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    """Return a cached Settings instance (one per process)."""
    return Settings()
